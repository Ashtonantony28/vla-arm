"""Regenerate CAD outputs: STEP + STL per printed part, a zero-pose assembly STEP, and
cad/out/cad_report.md with every automated check result.

    cd hardware && .venv/bin/python -m cad.build
"""
from __future__ import annotations

import datetime
import pathlib

import cadquery as cq

from . import assembly as A
from . import checks as C
from . import params as P
from . import parts as PT

OUT = pathlib.Path(__file__).resolve().parent / "out"


def export_parts() -> list[dict]:
    OUT.mkdir(exist_ok=True)
    rows = []
    for name, (_, link, mat) in PT.PRINTED.items():
        s = PT.build_printed(name, teeth=True)          # printable variant (real gear teeth)
        s_chk = PT.build_printed(name, teeth=False)     # pitch-envelope variant used by checks
        cq.exporters.export(s, str(OUT / f"{name}.step"))
        cq.exporters.export(s, str(OUT / f"{name}.stl"), tolerance=0.05, angularTolerance=0.2)
        bb = s.BoundingBox()
        fit, how = C.fits_bed(s)
        wt = C.wall_thickness(s_chk)
        rows.append(dict(name=name, link=link, material=mat, volume_cm3=s.Volume() / 1000,
                         mass_g=C.printed_mass_g(name, s), bbox=(bb.xlen, bb.ylen, bb.zlen),
                         fits=fit, orientation=how, wall_min=wt["min"], wall_p1=wt["p1"],
                         stl_kb=(OUT / f"{name}.stl").stat().st_size / 1024, **C.solid_report(s)))
    # servo placeholder for reference
    cq.exporters.export(PT.servo_body().fuse(PT.servo_horn()), str(OUT / "servo_placeholder_STS3215_APPROX.step"))
    # zero-pose assembly
    asm = cq.Assembly(name="vla_arm_zero_pose")
    for it, shp in A.posed({}, teeth=True):
        asm.add(shp, name=it.name, color=cq.Color(0.8, 0.5, 0.2) if it.printed else cq.Color(0.2, 0.2, 0.2))
    asm.save(str(OUT / "assembly_zero_pose.step"))
    return rows


def report(rows) -> str:
    L = []
    L.append("# CAD check report (generated by `python -m cad.build`; do not edit)\n")
    L.append(f"Generated {datetime.date.today().isoformat()}. All numbers come from the generated B-rep, "
             "not from hand calculation. Nothing here has been printed or measured.\n")
    L.append("## Printed parts\n")
    L.append("| part | link | mat | valid closed solid | volume cm3 | est. mass g | bbox mm | fits 220x220x250 | min wall mm (1st pct) | STL kB |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    tot = 0.0
    for r in rows:
        tot += r["mass_g"]
        ok = "yes" if (r["valid"] and r["closed"] and r["n_solids"] == 1) else "NO"
        L.append(f"| {r['name']} | {r['link']} | {r['material']} | {ok} | {r['volume_cm3']:.1f} | {r['mass_g']:.1f} | "
                 f"{r['bbox'][0]:.0f} x {r['bbox'][1]:.0f} x {r['bbox'][2]:.0f} | "
                 f"{'yes' if r['fits'] else 'NO'} ({r['orientation']}) | {r['wall_min']:.2f} ({r['wall_p1']:.2f}) | {r['stl_kb']:.0f} |")
    L.append(f"\nTotal printed mass estimate: **{tot:.0f} g** (PETG {P.DENSITY['PETG']} g/cm3 x "
             f"{P.INFILL_EFF:.0%} effective solid fraction; TPU pads solid).\n")
    L.append("## Link masses vs spec (g)\n")
    L.append("| link | printed | servos + purchased | total | spec | delta |")
    L.append("|---|---|---|---|---|---|")
    lm = C.link_masses()
    for k, v in lm.items():
        L.append(f"| {k} | {v['printed']:.0f} | {v['purchased']:.0f} | {v['total']:.0f} | {v['spec']:.0f} | {v['total'] - v['spec']:+.0f} |")
    tw = sum(v["total"] for v in lm.values()); ts = sum(v["spec"] for v in lm.values())
    wg = lm["wrist"]["total"] + lm["gripper"]["total"]; wgs = lm["wrist"]["spec"] + lm["gripper"]["spec"]
    L.append(f"| **all** | | | **{tw:.0f}** | **{ts:.0f}** | {tw - ts:+.0f} |")
    L.append(f"\nNote: in this design the wrist-roll servo CASE rides in the gripper (its horn is bolted to the "
             f"wrist bracket), so mass moves from `wrist` to `gripper`; wrist+gripper = {wg:.0f} g vs spec {wgs:.0f} g. "
             "Fasteners, wiring and heat-set inserts are not included (budget +5-10 % per link).\n")
    L.append("## Joint-axis distances measured from part geometry\n")
    L.append("| feature pair | measured mm | spec mm | error mm |")
    L.append("|---|---|---|---|")
    for k, (m, s) in C.measured_dimensions().items():
        L.append(f"| {k} | {m:.3f} | {s:.3f} | {m - s:+.3f} |")
    L.append("\n## Collision-free joint ranges (one joint swept, others at zero)\n")
    L.append("Adjacent = parent/child parts across the swept joint (incl. servo cases, horns, bearing). "
             "All = every part downstream of the joint vs every part upstream.\n")
    L.append("| joint | spec limits rad | adjacent-pair free range | all-pairs free range | within spec? |")
    L.append("|---|---|---|---|---|")
    for jn, lim in C.joint_limits().items():
        a = C.free_range(jn, True); b = C.free_range(jn, False)
        ok = "yes" if (abs(a[0] - lim[0]) < 1e-9 and abs(a[1] - lim[1]) < 1e-9) else "**NO**"
        L.append(f"| {jn} | [{lim[0]:+.2f}, {lim[1]:+.2f}] | [{a[0]:+.3f}, {a[1]:+.3f}] | [{b[0]:+.3f}, {b[1]:+.3f}] | {ok} |")
    L.append("\nShoulder: with the shoulder axis only 100 mm above the plate (spec) and the base housing the yaw "
             "servo under a 78 mm bearing, the upper arm reaches the base/turntable at about +0.80 rad (46 deg down); "
             "the spec limit +1.30 rad is not mechanically reachable. Elbow: folding down past ~+2.36 rad with the "
             "shoulder at zero drives the wrist into the base (a pose-dependent self-collision for the host-side "
             "checker, not an adjacent-part clash).\n")
    return "\n".join(L)


def main():
    rows = export_parts()
    (OUT / "cad_report.md").write_text(report(rows))
    print((OUT / "cad_report.md").read_text())


if __name__ == "__main__":
    main()
