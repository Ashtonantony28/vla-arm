import numpy as np

from spec_loader import load_spec


def spring_packaging(k, F_max, ext_max, G=79e3, tau_allow=800.0):
    """Shortest extension spring (music wire) with rate k N/mm reaching F_max at ext_max extension.
    Body = (n+1) d, each machine hook ~ 0.8 D. Returns the geometry and lengths (mm)."""
    best = None
    for d in np.arange(0.6, 2.51, 0.1):
        for c in np.arange(5.0, 14.01, 0.25):
            D = c * d
            kw = (4 * c - 1) / (4 * c - 4) + 0.615 / c
            if 8 * F_max * D / (math.pi * d ** 3) * kw > tau_allow:
                continue
            n = G * d ** 4 / (8 * D ** 3 * k)
            if n < 3:
                continue
            L_free = (n + 1) * d + 2 * 0.8 * D
            L_max = L_free + ext_max
            if best is None or L_max < best["L_max"]:
                best = dict(d=float(d), D=float(D), n=float(n), L_free=float(L_free), L_max=float(L_max),
                            tau_allow=tau_allow)
    return best
from .budget import (G, ArmModel, BusTiming, ServoRating, SpringDesign, gravity_torques,
                     minimax_balance, spring_torque)

OUT = pathlib.Path(__file__).resolve().parent / "budget_report.md"
YAW_ALPHA = 15.0       # rad/s^2, assumed peak yaw acceleration of a quintic move (~1 rad in 0.6 s)
GRIP_MU = 0.5          # TPU on dry objects (assumed)
GRIP_SF = 2.0          # safety factor on slip


def spec_rating(joint: str | None = None) -> ServoRating:
    """Servo rating of ``joint`` (spec v1.3: `servo_overrides` replaces the default per joint)."""
    spec = load_spec()
    s = dict(spec["servo"])
    s.update((spec.get("servo_overrides") or {}).get(joint, {}))
    return ServoRating(s["stall_torque_nm"], s["stall_current_a"], s["max_continuous_current_a"])


def servo_name(joint: str) -> str:
    o = (load_spec().get("servo_overrides") or {}).get(joint)
    return o["model"].split(",")[0] if o else "STS3215"


# The spring counterbalance studied up to spec v1.2 (pulley A 40 mm above the shoulder axis on a bracket
# post, pin B 70 mm along the upper arm, ~79 mm between the post foot and the pulley). Kept only to
# document why spec v1.3 replaced it with a stronger shoulder servo.
CB_A_MM, CB_B_MM, CB_POST_SPAN_MM = 40.0, 70.0, 79.0


def models():
    """Two models: spec masses (authoritative) and CAD-estimated masses; COMs from CAD in both."""
    from .cad_props import link_mass_props
    from cad import params as P
    spec = load_spec()
    mp = link_mass_props()
    L = (P.UPPER_ARM_L / 1000, P.FOREARM_L / 1000, (P.WRIST_L + P.TCP_L) / 1000)
    com = {k: (mp[k]["com_m"][0], mp[k]["com_m"][2]) for k in ("upper_arm", "forearm", "wrist")}
    gc = mp["gripper"]["com_m"]
    com["gripper"] = (P.WRIST_L / 1000 + gc[0], gc[2])   # gripper COM expressed in the wrist frame
    ms = spec["masses_kg"]
    m_spec = {k: ms[k] for k in ("upper_arm", "forearm", "wrist", "gripper")}
    m_cad = {k: mp[k]["mass_kg"] for k in ("upper_arm", "forearm", "wrist", "gripper")}
    return {"spec masses": ArmModel(L, m_spec, com, spec["payload_kg"]),
            "CAD masses": ArmModel(L, m_cad, com, spec["payload_kg"])}, mp


def limits():
    spec = load_spec()
    return {j["name"]: tuple(j["limits"]) for j in spec["joints"]}


def grid(model: ArmModel, q2_range, n2=40, n3=37, n4=21, payloads=(0.0, None)):
    lim = limits()
    rows = []
    for pl in payloads:
        mm = ArmModel(model.link_len, model.masses, model.coms, model.payload if pl is None else pl)
        for q2, q3, q4 in itertools.product(np.linspace(*q2_range, n2), np.linspace(*lim["elbow_pitch"], n3),
                                            np.linspace(*lim["wrist_pitch"], n4)):
            rows.append((q2, gravity_torques(mm, q2, q3, q4)["shoulder_pitch"]))
    a = np.array(rows)
    return a[:, 0], a[:, 1]


def build(q2_mech_max: float | None = None) -> str:
    spec = load_spec()
    rating = spec_rating()
    R = {j: spec_rating(j) for j in ("base_yaw", "shoulder_pitch", "elbow_pitch", "wrist_pitch", "wrist_roll", "gripper")}
    mods, mp = models()
    from cad import params as P
    lim = limits()
    if q2_mech_max is None:
        from cad import checks as C
        q2_mech_max = C.free_range("shoulder_pitch", adjacent_only=False)[1]
    q2_range = (lim["shoulder_pitch"][0], q2_mech_max)
    q2s, taus = grid(mods["spec masses"], q2_range)

    L = ["# Torque, power and bus-timing budget (generated by `python -m analysis.report`; do not edit)\n",
         f"Generated {datetime.date.today().isoformat()}. Inputs: spec/kinematics.yaml (masses, lengths, servo "
         f"ratings incl. `servo_overrides`, payload {spec['payload_kg']} kg); centres of mass from the generated CAD "
         "(hardware/cad). Nothing has been measured on hardware.\n"]

    # ---- static holding torque at full reach
    L.append("## 1. Static holding torque, arm stretched horizontally, payload at the TCP\n")
    sh = R["shoulder_pitch"]
    L.append(f"Servos: STS3215 stall {rating.stall_torque} N*m, continuous = {rating.derate:.0%} of stall = "
             f"{rating.cont_torque:.2f} N*m. Shoulder (spec v1.3): {servo_name('shoulder_pitch')}, stall "
             f"{sh.stall_torque} N*m, continuous {sh.cont_torque:.2f} N*m on the same 40 % rule (the listed "
             f"\"rated\" torque is {spec['servo_overrides']['shoulder_pitch']['rated_torque_nm']} N*m, so treat the "
             "shoulder's continuous figures as optimistic by ~20 %). No counterbalance spring (section 2).\n")
    L.append("| joint | model | servo | holding N*m | % stall | margin vs continuous | verdict |")
    L.append("|---|---|---|---|---|---|---|")
    summary = {}
    for name, m in mods.items():
        t = gravity_torques(m, 0, 0, 0)
        for j in ("shoulder_pitch", "elbow_pitch", "wrist_pitch"):
            r, t0 = R[j], abs(t[j])
            verdict = ("OK continuous" if t0 <= r.cont_torque else
                       ("intermittent only" if t0 <= r.stall_torque else "EXCEEDS STALL"))
            L.append(f"| {j} | {name} | {servo_name(j)} | {t0:.2f} | {100 * t0 / r.stall_torque:.0f} % | "
                     f"x{r.cont_torque / t0:.2f} | {verdict} |")
            summary[(j, name)] = t0
    gm = mp["gripper"]
    roll_t = (gm["mass_kg"]) * G * math.hypot(gm["com_m"][1], gm["com_m"][2])
    L.append(f"| wrist_roll | CAD | STS3215 | {roll_t:.3f} | {100 * roll_t / rating.stall_torque:.1f} % | x{rating.cont_torque / roll_t:.0f} | OK (payload on axis; gripper COM {1000 * math.hypot(gm['com_m'][1], gm['com_m'][2]):.0f} mm off axis) |")
    m = mods["spec masses"]
    pts = m.points(0, 0, 0)
    Izz = sum(m.masses[k] * pts[k][0] ** 2 for k in m.masses) + m.payload * pts["payload"][0] ** 2
    yaw_t = Izz * YAW_ALPHA
    L.append(f"| base_yaw | spec | STS3215 | 0 (vertical axis); dynamic: I_zz {Izz:.3f} kg*m^2 x {YAW_ALPHA:.0f} rad/s^2 = "
             f"{yaw_t:.2f} | {100 * yaw_t / rating.stall_torque:.0f} % | x{rating.cont_torque / yaw_t:.2f} | "
             f"{'OK' if yaw_t < rating.cont_torque else 'peak only; limit yaw accel at full reach'} |")
    F_grip = rating.stall_torque / (2 * P.PINION_R / 1000)
    F_need = spec["payload_kg"] * G * GRIP_SF / (2 * GRIP_MU)
    L.append(f"| gripper | - | STS3215 | squeeze force per jaw at stall {F_grip:.0f} N, at continuous {F_grip * rating.derate:.0f} N | "
             f"needed for {spec['payload_kg']} kg (mu {GRIP_MU}, SF {GRIP_SF}): {F_need:.1f} N | x{F_grip * rating.derate / F_need:.1f} | "
             "OK; set a gripper current limit so it cannot crush objects |")
    L.append("")
    L.append(f"Over the whole reachable pose set (shoulder in [{q2_range[0]:+.2f}, {q2_range[1]:+.2f}] rad, elbow and "
             "wrist over their full limits, payload 0 or the spec payload) the worst shoulder holding torque is "
             f"**{np.max(np.abs(taus)):.2f} N*m** = {100 * np.max(np.abs(taus)) / sh.stall_torque:.0f} % of the "
             f"{servo_name('shoulder_pitch')} stall torque.\n")
    mS = mods["spec masses"]
    arm_only = ArmModel(mS.link_len, mS.masses, mS.coms, 0.0)

    def max_payload(j):
        t_arm = gravity_torques(arm_only)[j]
        lever = gravity_torques(ArmModel(mS.link_len, {k: 0.0 for k in mS.masses}, mS.coms, 1.0))[j]
        return (R[j].cont_torque - t_arm) / lever
    L.append(f"Largest payload that the servos can hold CONTINUOUSLY (40 % derating) at full horizontal reach: "
             f"elbow **{max_payload('elbow_pitch'):.2f} kg**, shoulder **{max_payload('shoulder_pitch'):.2f} kg** "
             f"({servo_name('shoulder_pitch')}). The spec's {spec['payload_kg']} kg at full reach is therefore an "
             "intermittent (seconds) load for shoulder and elbow; for long data sessions keep heavy objects inside "
             "~80 % reach.\n")
    L.append("Bearing load (yaw): overturning moment at full reach with payload = "
             f"{abs(gravity_torques(mods['spec masses'])['shoulder_pitch']):.2f} N*m (spec masses) plus the shoulder "
             "bracket; carried by the 61816 thin-section bearing (80 x 100 x 10), not by the yaw servo.\n")

    # ---- why no spring
    K, worst = minimax_balance(taus, np.cos(q2s))
    real = SpringDesign(K, CB_A_MM / 1000, CB_B_MM / 1000).bounds(q2_range).realisation()
    pk = spring_packaging(real["k_N_per_mm"], real["F_max_N"], real["extension_max_mm"])
    L.append("## 2. Why there is no counterbalance spring (spec v1.3)\n")
    L.append(f"A zero-free-length spring (cable from a pin {CB_B_MM:.0f} mm along the upper arm over a pulley "
             f"{CB_A_MM:.0f} mm above the shoulder axis) sized minimax over the reachable poses needs K = k*a*b = "
             f"{K:.2f} N*m: rate {real['k_N_per_mm']:.2f} N/mm, up to {real['F_max_N']:.0f} N, "
             f"{real['extension_max_mm']:.0f} mm extension. The shortest music-wire extension spring for that "
             f"(static shear <= {pk['tau_allow']:.0f} MPa: wire {pk['d']:.1f} mm, mean dia {pk['D']:.1f} mm) is "
             f"**{pk['L_max']:.0f} mm long at full extension**, against ~{CB_POST_SPAN_MM:.0f} mm available on the "
             "shoulder bracket. Taller posts, a moved pin, 2:1 reeving, parallel springs and partial balance were "
             "all checked and none fits, because the spring has to store ~1.9 J. The spring, post, pulley and pin "
             "were therefore removed and the shoulder servo became an STS3250 (same case, 4.9 N*m stall): "
             "spec/DECISIONS.md, v1.3.\n")

    # ---- current budget
    L.append("## 3. 12 V servo-rail current budget\n")
    t_full = gravity_torques(mods["CAD masses"])
    t_full_s = gravity_torques(mods["spec masses"])
    hold = {j: max(abs(t_full[j]), abs(t_full_s[j])) for j in ("shoulder_pitch", "elbow_pitch", "wrist_pitch")}
    joints6 = ["base_yaw", "shoulder_pitch", "elbow_pitch", "wrist_pitch", "wrist_roll", "gripper"]
    tau_static = {j: hold.get(j, 0.0) for j in joints6}; tau_static["wrist_roll"] = roll_t
    I0 = {j: R[j].current_for(t) for j, t in tau_static.items()}
    L.append(f"Linear current model per servo: I = {rating.idle_current} A idle (assumed) + (I_stall - idle) x "
             "tau/tau_stall (STS3250 stall current 4.2 A from retailer listings; verify).\n")
    L.append("| joint | servo | static tau N*m | I (A) | stall I (A) |")
    L.append("|---|---|---|---|---|")
    for j in joints6:
        L.append(f"| {j} | {servo_name(j)} | {tau_static[j]:.2f} | {I0[j]:.2f} | {R[j].stall_current:.1f} |")
    elec_w = 0.33 * 0.1 + 5.0 * 0.12      # 3.3 V ~100 mA + 5 V ~120 mA (CAN transceiver dominant)
    I_elec = elec_w / 0.85 / 12.0
    s0 = sum(I0.values())
    I_stall_all = sum(R[j].stall_current for j in joints6)
    # dynamic allowance: the two biggest servos accelerating at 80 % of stall on top of holding
    I_dyn = 0.8 * sum(sorted((R[j].stall_current for j in joints6), reverse=True)[:2])
    L.append(f"| **sum static** | | | **{s0:.2f}** | **{I_stall_all:.1f}** |")
    L.append(f"\nBoard electronics (5 V + 3.3 V bucks, ~{elec_w:.2f} W at 85 %): {I_elec:.2f} A at 12 V.\n")
    I_design = s0 + I_dyn + I_elec
    L.append("| case | 12 V current |")
    L.append("|---|---|")
    L.append(f"| static hold at full reach + payload | {s0 + I_elec:.1f} A |")
    L.append(f"| typical worst motion: static + the two largest servos accelerating at 80 % stall | {I_design:.1f} A |")
    L.append(f"| absolute worst: all six servos stalled at once | {I_stall_all + I_elec:.1f} A |")
    L.append(f"\n**PSU recommendation:** 12 V, **>= 12.5 A continuous (150 W)**, with a peak rating >= "
             f"{math.ceil(I_stall_all + I_elec):.0f} A for >= 100 ms or a hard current limit that does not latch off. "
             f"Rationale: the realistic worst motion is ~{I_design:.0f} A; an all-servo stall "
             f"({I_stall_all + I_elec:.0f} A) exceeds a 12.5 A brick, so the firmware current limits must keep "
             "the sum below it. Firmware/servo settings: per-servo protection current ~2.0 A (~3.0 A for the "
             "STS3250 shoulder), board OVERCURRENT fault at 12 A sustained > 20 ms on the INA240 reading. Input "
             "fuse 15 A slow-blow. Bulk capacitance on the servo rail (>= 1000 uF low-ESR) covers sub-millisecond "
             "stall edges only, not sustained stalls.\n")

    # ---- bus timing
    L.append("## 4. Servo bus timing (spec/protocol.md: 1 kHz loop, 1 Mbps, SYNC_WRITE 6 + 1 read per cycle)\n")
    for label, bt in (("goal position only (2 B/servo)", BusTiming()),
                      ("position + time + speed (6 B/servo)", BusTiming(write_bytes_per_servo=6))):
        b = bt.budget()
        L.append(f"### {label}\n")
        L.append("| item | us |")
        L.append("|---|---|")
        for k, v in b["items"].items():
            L.append(f"| {k} | {v:.0f} |")
        L.append(f"| **total** | **{b['total_us']:.0f}** ({b['utilisation']:.0%} of the 1000 us cycle, margin {b['margin_us']:.0f} us) |\n")
    L.append("8N1 framing (10 bits/byte). The read covers registers 0x38-0x46 (present position, speed, load, "
             "voltage, temperature, status, moving, present current) in one READ so the STATE frame gets pos/vel/"
             "current/temp from one transaction. Feetech packet layout as in the SCS/STS protocol (Dynamixel-1.0-"
             "like); register addresses are from the STS3215 memory table as commonly published and must be "
             "checked against the servo's datasheet. Servo response latency is ASSUMED (100 us); measure it on the "
             "first servo with a logic analyser. Verdict: fits in 1 ms with the 2-byte write; the 6-byte write "
             "is tight but fits; there is no room for a second read per cycle.\n")
    return "\n".join(L)


def main():
    OUT.write_text(build())
    print(OUT.read_text())


if __name__ == "__main__":
    main()
