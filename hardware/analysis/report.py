"""Generate analysis/budget_report.md:  cd hardware && .venv/bin/python -m analysis.report"""
from __future__ import annotations

import datetime
import itertools
import math
import pathlib

import numpy as np

from spec_loader import load_spec
from .budget import (G, ArmModel, BusTiming, ServoRating, SpringDesign, gravity_torques,
                     minimax_balance, spring_torque)

OUT = pathlib.Path(__file__).resolve().parent / "budget_report.md"
YAW_ALPHA = 15.0       # rad/s^2, assumed peak yaw acceleration of a quintic move (~1 rad in 0.6 s)
GRIP_MU = 0.5          # TPU on dry objects (assumed)
GRIP_SF = 2.0          # safety factor on slip


def spec_rating() -> ServoRating:
    s = load_spec()["servo"]
    return ServoRating(s["stall_torque_nm"], s["stall_current_a"], s["max_continuous_current_a"])


def models():
    """Two models: spec masses (authoritative) and CAD-estimated masses; COMs from CAD in both."""
    from .cad_props import link_mass_props
    from cad import params as P
    spec = load_spec()
    mp = link_mass_props()
    L = (P.UPPER_ARM_L / 1000, P.FOREARM_L / 1000, (P.WRIST_L + P.TCP_L) / 1000)
    com = {k: (mp[k]["com_m"][0], mp[k]["com_m"][2]) for k in ("upper_arm", "forearm", "wrist")}
    gc = mp["gripper"]["com_m"]
    com["gripper"] = (P.WRIST_L / 1000 + gc[0], gc[2])   # gripper COM expressed in the wrist frame
    ms = spec["masses_kg"]
    m_spec = {k: ms[k] for k in ("upper_arm", "forearm", "wrist", "gripper")}
    m_cad = {k: mp[k]["mass_kg"] for k in ("upper_arm", "forearm", "wrist", "gripper")}
    return {"spec masses": ArmModel(L, m_spec, com, spec["payload_kg"]),
            "CAD masses": ArmModel(L, m_cad, com, spec["payload_kg"])}, mp


def limits():
    spec = load_spec()
    return {j["name"]: tuple(j["limits"]) for j in spec["joints"]}


def grid(model: ArmModel, q2_range, n2=40, n3=37, n4=21, payloads=(0.0, None)):
    lim = limits()
    rows = []
    for pl in payloads:
        mm = ArmModel(model.link_len, model.masses, model.coms, model.payload if pl is None else pl)
        for q2, q3, q4 in itertools.product(np.linspace(*q2_range, n2), np.linspace(*lim["elbow_pitch"], n3),
                                            np.linspace(*lim["wrist_pitch"], n4)):
            rows.append((q2, gravity_torques(mm, q2, q3, q4)["shoulder_pitch"]))
    a = np.array(rows)
    return a[:, 0], a[:, 1]


def build(q2_mech_max: float | None = None) -> str:
    spec = load_spec()
    rating = spec_rating()
    mods, mp = models()
    from cad import params as P
    lim = limits()
    if q2_mech_max is None:
        from cad import checks as C
        q2_mech_max = C.free_range("shoulder_pitch", adjacent_only=False)[1]
    q2_range = (lim["shoulder_pitch"][0], q2_mech_max)

    # ---- counterbalance sized on the spec-mass model, minimax over the reachable pose set
    q2s, taus = grid(mods["spec masses"], q2_range)
    K, worst = minimax_balance(taus, np.cos(q2s))
    q2s_c, taus_c = grid(mods["CAD masses"], q2_range)
    worst_cad = float(np.max(np.abs(taus_c - K * np.cos(q2s_c))))
    sp = SpringDesign(K, P.CB["a"] / 1000, P.CB["b"] / 1000).bounds(q2_range)
    real = sp.realisation()
    sp_spec = SpringDesign(K, P.CB["a"] / 1000, P.CB["b"] / 1000).bounds(lim["shoulder_pitch"]).realisation()

    L = ["# Torque, power and bus-timing budget (generated by `python -m analysis.report`; do not edit)\n",
         f"Generated {datetime.date.today().isoformat()}. Inputs: spec/kinematics.yaml (masses, lengths, servo "
         f"rating, payload {spec['payload_kg']} kg); centres of mass from the generated CAD "
         "(hardware/cad). Nothing has been measured on hardware.\n"]

    # ---- static holding torque at full reach
    L.append("## 1. Static holding torque, arm stretched horizontally, payload at the TCP\n")
    L.append(f"Servo: stall {rating.stall_torque} N*m; continuous = {rating.derate:.0%} of stall = "
             f"{rating.cont_torque:.2f} N*m (the spec's 1.0 A max continuous current corresponds to "
             f"~{rating.stall_torque * rating.max_cont_current / rating.stall_current:.2f} N*m on a linear "
             "torque-constant model, so the 40 % derating is the slightly optimistic one).\n")
    L.append(f"Counterbalance: zero-free-length spring, K = k*a*b = **{K:.3f} N*m**, chosen to minimise the worst "
             f"residual shoulder torque over all poses with shoulder in [{q2_range[0]:+.2f}, {q2_range[1]:+.2f}] rad "
             "(the mechanically reachable range), elbow and wrist over their full limits, payload 0 or 0.25 kg.\n")
    L.append("| joint | model | holding N*m (no CB) | with CB | % stall (no CB / CB) | margin vs continuous (no CB / CB) | verdict |")
    L.append("|---|---|---|---|---|---|---|")
    summary = {}
    for name, m in mods.items():
        t = gravity_torques(m, 0, 0, 0)
        for j in ("shoulder_pitch", "elbow_pitch", "wrist_pitch"):
            t0 = abs(t[j])
            t1 = abs(t[j] - spring_torque(K, 0.0)) if j == "shoulder_pitch" else t0
            mc0, mc1 = rating.cont_torque / t0, rating.cont_torque / max(t1, 1e-9)
            verdict = ("OK continuous" if t1 <= rating.cont_torque else
                       ("intermittent only" if t1 <= rating.stall_torque else "EXCEEDS STALL"))
            L.append(f"| {j} | {name} | {t0:.2f} | {t1:.2f} | {100 * t0 / rating.stall_torque:.0f} % / "
                     f"{100 * t1 / rating.stall_torque:.0f} % | x{mc0:.2f} / x{mc1:.2f} | {verdict} |")
            summary[(j, name)] = (t0, t1)
    # roll + yaw + gripper
    gm = mp["gripper"]
    roll_t = (gm["mass_kg"]) * G * math.hypot(gm["com_m"][1], gm["com_m"][2])
    L.append(f"| wrist_roll | CAD | {roll_t:.3f} | - | {100 * roll_t / rating.stall_torque:.1f} % | x{rating.cont_torque / roll_t:.0f} | OK (payload on axis; gripper COM {1000 * math.hypot(gm['com_m'][1], gm['com_m'][2]):.0f} mm off axis) |")
    m = mods["spec masses"]
    pts = m.points(0, 0, 0)
    Izz = sum(m.masses[k] * pts[k][0] ** 2 for k in m.masses) + m.payload * pts["payload"][0] ** 2
    yaw_t = Izz * YAW_ALPHA
    L.append(f"| base_yaw | spec | 0 (vertical axis) | - | dynamic: I_zz {Izz:.3f} kg*m^2 x {YAW_ALPHA:.0f} rad/s^2 = "
             f"{yaw_t:.2f} N*m ({100 * yaw_t / rating.stall_torque:.0f} % stall) | x{rating.cont_torque / yaw_t:.2f} | "
             f"{'OK' if yaw_t < rating.cont_torque else 'peak only; limit yaw accel at full reach'} |")
    F_grip = rating.stall_torque / (2 * P.PINION_R / 1000)
    F_need = spec["payload_kg"] * G * GRIP_SF / (2 * GRIP_MU)
    L.append(f"| gripper | - | squeeze force per jaw at stall {F_grip:.0f} N, at continuous {F_grip * rating.derate:.0f} N | - | "
             f"needed for 0.25 kg (mu {GRIP_MU}, SF {GRIP_SF}): {F_need:.1f} N | x{F_grip * rating.derate / F_need:.1f} | OK; set a "
             "gripper current limit so it cannot crush objects |")
    L.append("")
    L.append("Over the whole reachable pose set the worst residual shoulder torque WITH the counterbalance is "
             f"**{worst:.2f} N*m** (spec masses) / {worst_cad:.2f} N*m (CAD masses); without it the worst is "
             f"{np.max(np.abs(taus)):.2f} N*m.\n")
    # alternative balance choices
    mS = mods["spec masses"]
    arm_only = ArmModel(mS.link_len, mS.masses, mS.coms, 0.0)
    K_arm = gravity_torques(arm_only)["shoulder_pitch"]
    K_half = gravity_torques(ArmModel(mS.link_len, mS.masses, mS.coms, mS.payload / 2))["shoulder_pitch"]
    L.append("Counterbalance options (spec masses):\n")
    L.append("| choice | K (N*m) | residual at full reach, payload 0.25 kg | worst residual over all reachable poses |")
    L.append("|---|---|---|---|")
    for lab, k_ in (("minimax over all poses (chosen)", K), ("balance stretched arm, no payload", K_arm),
                    ("balance stretched arm + half payload", K_half)):
        r_full = abs(gravity_torques(mS)["shoulder_pitch"] - k_)
        L.append(f"| {lab} | {k_:.2f} | {r_full:.2f} | {float(np.max(np.abs(taus - k_ * np.cos(q2s)))):.2f} |")
    L.append("\nA larger K helps the common stretched poses but over-lifts when the elbow is folded back with the "
             "shoulder near horizontal; the minimax choice guarantees no reachable pose is worse than "
             f"{worst:.2f} N*m. K can be tuned later simply by moving pin B (K is proportional to b).\n")
    # max payload for continuous holding at full reach
    def max_payload(j, Kcb):
        t_arm = gravity_torques(arm_only)[j] - (Kcb if j == "shoulder_pitch" else 0.0)
        lever = gravity_torques(ArmModel(mS.link_len, {k: 0.0 for k in mS.masses}, mS.coms, 1.0))[j]
        return (rating.cont_torque - t_arm) / lever
    L.append(f"Largest payload that the servos can hold CONTINUOUSLY (40 % derating) at full horizontal reach: "
             f"elbow **{max_payload('elbow_pitch', 0):.2f} kg**, shoulder {max_payload('shoulder_pitch', 0):.2f} kg without / "
             f"**{max_payload('shoulder_pitch', K):.2f} kg** with the counterbalance. The spec's 0.25 kg at full reach is "
             "therefore an intermittent (seconds) load for shoulder and elbow; for long data sessions keep heavy "
             "objects inside ~80 % reach or lower the rated payload.\n")
    L.append("Bearing load (yaw): overturning moment at full reach with payload = "
             f"{abs(gravity_torques(mods['spec masses'])['shoulder_pitch']):.2f} N*m (spec masses) plus the shoulder "
             "bracket; carried by the 61812 thin-section bearing, not by the yaw servo.\n")

    # ---- spring
    L.append("## 2. Shoulder counterbalance spring\n")
    L.append(f"Geometry (from CAD): pulley A {P.CB['a']:.0f} mm above the shoulder axis on the bracket post; pin B "
             f"{P.CB['b']:.0f} mm along the upper arm. Torque k*a*b*cos(q_shoulder) matches the cos-shaped gravity "
             "torque of the stretched arm at every shoulder angle (a zero-free-length spring), independent of yaw.\n")
    L.append("| quantity | reachable range | full spec range |")
    L.append("|---|---|---|")
    for key, lab in (("k_N_per_mm", "rate k (N/mm)"), ("Fi_N", "initial tension Fi (N), = k x 0.8 x min AB"),
                     ("ab_min_mm", "min distance AB (mm)"), ("ab_max_mm", "max distance AB (mm)"),
                     ("extension_max_mm", "spring extension at max (mm)"), ("F_max_N", "max spring force (N)")):
        L.append(f"| {lab} | {real[key]:.2f} | {sp_spec[key]:.2f} |")
    L.append("\nRealisation: cable from pin B over a ~10 mm pulley at A, down the post to an extension spring hooked "
             "at the post foot. Setting the cable length so the spring extension is AB - Fi/k makes the force "
             "exactly k*|AB| (equivalent zero free length) as long as the spring never goes slack. Choose a "
             f"spring with rate ~{real['k_N_per_mm']:.2f} N/mm, initial tension <= {real['k_N_per_mm'] * real['ab_min_mm']:.0f} N "
             f"and >= {real['extension_max_mm']:.0f} mm safe working extension (two springs in parallel at half "
             "rate are fine). No spring part number is given: pick from a catalogue and re-run this report with "
             "the real rate. The post and pin see up to the max spring force above.\n")

    # ---- current budget
    L.append("## 3. 12 V servo-rail current budget\n")
    t_full = gravity_torques(mods["CAD masses"])
    t_full_s = gravity_torques(mods["spec masses"])
    hold = {j: max(abs(t_full[j]), abs(t_full_s[j])) for j in ("shoulder_pitch", "elbow_pitch", "wrist_pitch")}
    hold_cb = dict(hold); hold_cb["shoulder_pitch"] = max(summary[("shoulder_pitch", n)][1] for n in mods)
    joints6 = ["base_yaw", "shoulder_pitch", "elbow_pitch", "wrist_pitch", "wrist_roll", "gripper"]
    tau_static = {j: hold.get(j, 0.0) for j in joints6}; tau_static["wrist_roll"] = roll_t
    tau_static_cb = dict(tau_static); tau_static_cb["shoulder_pitch"] = hold_cb["shoulder_pitch"]
    I0 = {j: rating.current_for(t) for j, t in tau_static.items()}
    I1 = {j: rating.current_for(t) for j, t in tau_static_cb.items()}
    L.append(f"Linear current model I = {rating.idle_current} A idle (assumed) + (I_stall - idle) x tau/tau_stall.\n")
    L.append("| joint | static tau N*m (no CB) | I (A) no CB | I (A) with CB | stall I (A) |")
    L.append("|---|---|---|---|---|")
    for j in joints6:
        L.append(f"| {j} | {tau_static[j]:.2f} | {I0[j]:.2f} | {I1[j]:.2f} | {rating.stall_current:.1f} |")
    elec_w = 0.33 * 0.1 + 5.0 * 0.12      # 3.3 V ~100 mA + 5 V ~120 mA (CAN transceiver dominant)
    I_elec = elec_w / 0.85 / 12.0
    s0, s1 = sum(I0.values()), sum(I1.values())
    I_stall_all = 6 * rating.stall_current
    # dynamic allowance: two biggest joints accelerating at 80 % of stall on top of holding
    I_dyn = 2 * 0.8 * rating.stall_current
    L.append(f"| **sum static** | | **{s0:.2f}** | **{s1:.2f}** | **{I_stall_all:.1f}** |")
    L.append(f"\nBoard electronics (5 V + 3.3 V bucks, ~{elec_w:.2f} W at 85 %): {I_elec:.2f} A at 12 V.\n")
    I_design = s0 + I_dyn + I_elec
    L.append("| case | 12 V current |")
    L.append("|---|---|")
    L.append(f"| static hold at full reach + payload, no CB | {s0 + I_elec:.1f} A |")
    L.append(f"| static hold, with CB | {s1 + I_elec:.1f} A |")
    L.append(f"| typical worst motion: static (no CB) + two joints accelerating at 80 % stall | {I_design:.1f} A |")
    L.append(f"| absolute worst: all six servos stalled at once | {I_stall_all + I_elec:.1f} A |")
    L.append("\n**PSU recommendation:** 12 V, **>= 12.5 A continuous (150 W)**, with a peak rating >= 16 A for >= 100 ms "
             f"or a hard current limit that does not latch off. Rationale: the realistic worst motion is ~{I_design:.0f} A; "
             f"an all-servo stall ({I_stall_all + I_elec:.0f} A) exceeds a 10 A brick, which would brown out the board. "
             "The spec PLAN's 12 V 10 A supply is the bare minimum and only works if the firmware current limits "
             "keep the sum below 10 A. Firmware/servo settings: per-servo protection current ~2.0 A, board OVERCURRENT "
             "fault at 12 A sustained > 20 ms on the INA240 reading. Input fuse 15 A slow-blow. Bulk capacitance "
             "on the servo rail (>= 1000 uF low-ESR) covers sub-millisecond stall edges only, not sustained stalls.\n")

    # ---- bus timing
    L.append("## 4. Servo bus timing (spec/protocol.md: 1 kHz loop, 1 Mbps, SYNC_WRITE 6 + 1 read per cycle)\n")
    for label, bt in (("goal position only (2 B/servo)", BusTiming()),
                      ("position + time + speed (6 B/servo)", BusTiming(write_bytes_per_servo=6))):
        b = bt.budget()
        L.append(f"### {label}\n")
        L.append("| item | us |")
        L.append("|---|---|")
        for k, v in b["items"].items():
            L.append(f"| {k} | {v:.0f} |")
        L.append(f"| **total** | **{b['total_us']:.0f}** ({b['utilisation']:.0%} of the 1000 us cycle, margin {b['margin_us']:.0f} us) |\n")
    L.append("8N1 framing (10 bits/byte). The read covers registers 0x38-0x46 (present position, speed, load, "
             "voltage, temperature, status, moving, present current) in one READ so the STATE frame gets pos/vel/"
             "current/temp from one transaction. Feetech packet layout as in the SCS/STS protocol (Dynamixel-1.0-"
             "like); register addresses are from the STS3215 memory table as commonly published and must be "
             "checked against the servo's datasheet. Servo response latency is ASSUMED (100 us); measure it on the "
             "first servo with a logic analyser. Verdict: fits in 1 ms with the 2-byte write; the 6-byte write "
             "is tight but fits; there is no room for a second read per cycle.\n")
    return "\n".join(L)


def main():
    OUT.write_text(build())
    print(OUT.read_text())


if __name__ == "__main__":
    main()
