"""Generate board outputs into board/out/:
  controller.net   KiCad netlist (SKiDL, KiCad 8 format)
  bom.csv          grouped BOM with MPN status
  mcu_pins.md      MCU pin-assignment table with AF numbers and confidence
  erc_report.md    own ERC + SKiDL ERC summary + netlist stats

    cd hardware && .venv/bin/python -m board.generate
"""
from __future__ import annotations

import contextlib
import csv
import io
import json
import os
import pathlib
from collections import OrderedDict

from . import erc, schematic
from .library import MCU_PADS
from .pinmap import ASSIGNMENTS, AVOIDED

OUT = pathlib.Path(__file__).resolve().parent / "out"
# commodity parts: any part matching the description is fine
GENERIC = {"R0603", "R0402", "C0402", "C0603", "C1206", "LED", "TP", "JUMPER2", "CONN_UART"}


@contextlib.contextmanager
def _in_out_dir():
    OUT.mkdir(exist_ok=True)
    cwd = os.getcwd()
    os.chdir(OUT)
    try:
        yield
    finally:
        os.chdir(cwd)


def stats(board) -> dict:
    nets = board.circuit.get_nets()
    return dict(parts=len(board.circuit.parts), nets=len(nets),
                connections=sum(len(n.pins) for n in nets),
                ics=sum(1 for m in board.meta.values() if m["meta"].is_ic))


def bom_rows(board):
    groups: "OrderedDict[tuple, list]" = OrderedDict()
    for p in sorted(board.circuit.parts, key=lambda p: (p.ref_prefix, len(p.ref), p.ref)):
        m = board.meta[p.ref]
        mt = m["meta"]
        key = (m["value"], p.footprint, mt.mpn, mt.desc)
        groups.setdefault(key, []).append(p.ref)
    rows = []
    for (value, fp, mpn, desc), refs in groups.items():
        mt = board.meta[refs[0]]["meta"]
        key = board.meta[refs[0]]["key"]
        status = mt.mpn_status if mpn else ("generic" if key in GENERIC else "TBD")
        rows.append(dict(refs=" ".join(refs), qty=len(refs), value=value, description=desc, footprint=fp,
                         manufacturer=mt.mfr, mpn=mpn, mpn_status=status))
    return rows


def run_skidl_erc() -> dict:
    """Run SKiDL's own ERC and collect its messages through a logging handler."""
    import logging
    import skidl
    msgs: list[str] = []

    class _H(logging.Handler):
        def emit(self, rec):
            msgs.append(f"ERC {rec.levelname}: {rec.getMessage()}")

    lg = logging.getLogger("ERC_Logger")
    h = _H(level=logging.DEBUG)
    lg.addHandler(h)
    try:
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            skidl.ERC()
    finally:
        lg.removeHandler(h)
    errs = sorted({m for m in msgs if m.startswith("ERC ERROR")})
    warns = sorted({m for m in msgs if m.startswith("ERC WARNING")})
    return dict(errors=errs, warnings=warns)


def generate():
    with _in_out_dir():
        board = schematic.build()
        findings = erc.check(board)
        sk = run_skidl_erc()
        import skidl
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            skidl.generate_netlist(file_=str(OUT / "controller.net"))
        for junk in list(OUT.glob("*_sklib.py")) + list(OUT.glob("*.erc")) + list(OUT.glob("*.log")):
            junk.unlink()
    st = stats(board)
    rows = bom_rows(board)
    with open(OUT / "bom.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader(); w.writerows(rows)
    (OUT / "stats.json").write_text(json.dumps(st, indent=1))

    # ---- MCU pin table
    pad = {nm: n for n, nm in MCU_PADS}
    L = ["# STM32G474RET6 (LQFP-64) pin assignment (generated by `python -m board.generate`)\n",
         "AF numbers are from the author's knowledge of DS12288, not from a downloaded datasheet. "
         "LQFP-64 pad numbers are recalled and UNVERIFIED (the netlist connects by pin NAME). "
         "Rows marked **verify** must be confirmed in STM32CubeMX before layout.\n",
         "| signal | pin | LQFP-64 pad (unverified) | function | AF | confidence | note |", "|---|---|---|---|---|---|---|"]
    for a in ASSIGNMENTS:
        conf = a.confidence if a.confidence == "high" else f"**verify** ({a.confidence})"
        L.append(f"| {a.signal} | {a.pin} | {pad[a.pin]} | {a.function} | {a.af} | {conf} | {a.note} |")
    L.append("\nPins deliberately avoided:\n")
    L += [f"- {k}: {v}" for k, v in AVOIDED.items()]
    L.append("\nPower pins: VDD x4, VBAT -> +3V3 (100 nF each + 4.7 uF); VDDA, VREF+ -> +3V3A via ferrite "
             "(1 uF + 10 nF + 100 nF); VSS x4, VSSA -> GND.\n")
    (OUT / "mcu_pins.md").write_text("\n".join(L))

    # ---- ERC report
    errs = [f for f in findings if f.level == "error"]
    warns = [f for f in findings if f.level != "error"]
    R = ["# Board ERC report (generated by `python -m board.generate`)\n",
         f"Netlist: {st['parts']} parts, {st['nets']} nets, {st['connections']} pin connections, {st['ics']} ICs.\n",
         f"## Own ERC (board/erc.py): {len(errs)} errors, {len(warns)} warnings\n"]
    R += [f"- ERROR {f.rule}: {f.msg}" for f in errs] or ["- no errors"]
    R += [f"- warning {f.rule}: {f.msg}" for f in warns]
    R.append(f"\n## SKiDL built-in ERC: {len(sk['errors'])} errors, {len(sk['warnings'])} warnings\n")
    unused = [l for l in sk["warnings"] if "Unconnected pin" in l and "STM32G474" in l]
    other = [l for l in sk["warnings"] if l not in unused]
    R += [f"- {l}" for l in sk["errors"] + other]
    R.append(f"- {len(unused)} warnings = unused STM32 GPIOs left unconnected (intended; spare pins, "
             "route to a header or leave as NC in KiCad)")
    unver = [r for r in rows if r["mpn_status"] in ("verify", "TBD")]
    R.append(f"\n## BOM lines needing a human check: {len(unver)} of {len(rows)}\n")
    R += [f"- {r['refs']}: {r['description']} -> {r['manufacturer']} {r['mpn'] or '(no part chosen)'} [{r['mpn_status']}]"
          for r in unver]
    (OUT / "erc_report.md").write_text("\n".join(R) + "\n")
    return board, findings, sk, st


def main():
    _, findings, sk, st = generate()
    print((OUT / "erc_report.md").read_text())


if __name__ == "__main__":
    main()
